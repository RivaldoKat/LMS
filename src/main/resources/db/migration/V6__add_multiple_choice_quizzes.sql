ALTER TABLE quiz_questions
    ADD COLUMN question_type VARCHAR(32) NOT NULL DEFAULT 'WRITTEN',
    ADD COLUMN correct_option_id BIGINT;

CREATE TABLE quiz_question_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL,
    option_text TEXT NOT NULL,
    option_order INTEGER NOT NULL,
    CONSTRAINT fk_quiz_question_options_question
        FOREIGN KEY (question_id) REFERENCES quiz_questions (id) ON DELETE CASCADE
);

ALTER TABLE quiz_questions
    ADD CONSTRAINT fk_quiz_questions_correct_option
        FOREIGN KEY (correct_option_id) REFERENCES quiz_question_options (id);

ALTER TABLE quiz_answers
    ADD COLUMN selected_option_id BIGINT,
    ADD CONSTRAINT fk_quiz_answers_selected_option
        FOREIGN KEY (selected_option_id) REFERENCES quiz_question_options (id);
