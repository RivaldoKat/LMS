CREATE TABLE quizzes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    opens_at TIMESTAMP WITH TIME ZONE NOT NULL,
    closes_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_quizzes_course FOREIGN KEY (course_id) REFERENCES courses (id)
);

CREATE TABLE quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL,
    prompt TEXT NOT NULL,
    max_points DOUBLE PRECISION NOT NULL CHECK (max_points > 0),
    CONSTRAINT fk_quiz_questions_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes (id) ON DELETE CASCADE
);

CREATE TABLE quiz_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL,
    learner_id BIGINT NOT NULL,
    submitted_at TIMESTAMP NOT NULL,
    graded_at TIMESTAMP,
    grade DOUBLE PRECISION CHECK (grade >= 0),
    feedback TEXT,
    status VARCHAR(32) NOT NULL,
    CONSTRAINT fk_quiz_attempts_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_attempts_learner FOREIGN KEY (learner_id) REFERENCES users (id),
    CONSTRAINT uq_quiz_attempt_learner UNIQUE (quiz_id, learner_id)
);

CREATE TABLE quiz_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    response_text TEXT NOT NULL,
    CONSTRAINT fk_quiz_answers_attempt FOREIGN KEY (attempt_id) REFERENCES quiz_attempts (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_answers_question FOREIGN KEY (question_id) REFERENCES quiz_questions (id),
    CONSTRAINT uq_quiz_answer_question UNIQUE (attempt_id, question_id)
);

CREATE INDEX idx_quizzes_course_id ON quizzes (course_id);
CREATE INDEX idx_quiz_attempts_learner_id ON quiz_attempts (learner_id);
